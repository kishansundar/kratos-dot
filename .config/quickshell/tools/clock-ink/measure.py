"""Read the clock ink probe's captures (light and dark) and write bar/ClockInk.js: for every string the clock shows,
where its ink starts and ends, in px from the Text's x, averaged over the two modes.
usage: python3 measure.py light.png dark.png out.js   (captures of the probe window at its top-left corner, scale 1)
An edge is area-weighted: a column a third covered moves the edge two thirds of a pixel inward."""
import sys, json
from PIL import Image

counts = [f"{n:02d}" for n in range(60)]
days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
dates = [str(n) for n in range(1, 10)]
cells = [(s, 20 + (i % 10) * 80, 20 + (i // 10) * 40, 80, 34) for i, s in enumerate(counts)]
cells += [(s, 20 + i * 120, 280, 120, 20) for i, s in enumerate(days)]
cells += [(s, 20 + i * 40, 320, 40, 20) for i, s in enumerate(dates)]

def edges(path):
    im = Image.open(path).convert("L"); px = im.load()
    bg = px[5, 5]
    out = {}
    for s, x, y, w, h in cells:
        cov = []
        for cx in range(x - 4, x + w - 4):
            col = max(abs(px[cx, cy] - bg) for cy in range(y, y + h))
            cov.append(col)
        full = max(cov)
        c = [min(1.0, v / full) for v in cov]
        first = next(i for i, v in enumerate(c) if v > 0.02)
        last = max(i for i, v in enumerate(c) if v > 0.02)
        left = first
        i = first
        while i <= last and c[i] < 0.98: left += 1 - c[i]; i += 1
        right = last + 1
        i = last
        while i >= first and c[i] < 0.98: right -= 1 - c[i]; i -= 1
        out[s] = (round(left - 4, 2), round(right - 4, 2))
    return out

a, b = edges(sys.argv[1]), edges(sys.argv[2])
avg = {s: (round((a[s][0] + b[s][0]) / 2, 2), round((a[s][1] + b[s][1]) / 2, 2)) for s in a}
spread = max(max(abs(a[s][0] - b[s][0]), abs(a[s][1] - b[s][1])) for s in a)
js = ["// Generated by tools/clock-ink/measure.py: where each clock string's ink starts and ends, in px from its Text's x,",
      "// read from Geist as the bar renders it (NativeRendering, light and dark averaged; largest light/dark difference",
      f"// {spread:.2f} px). bar/Clock places the hours, minutes, weekday and date by these. Regenerate after a font change.",
      ".pragma library",
      "var countLeft = " + json.dumps({s: avg[s][0] for s in counts}) + ";",
      "var countRight = " + json.dumps({s: avg[s][1] for s in counts}) + ";",
      "var dayRight = " + json.dumps({s: avg[s][1] for s in days}) + ";",
      "var dateLeft = " + json.dumps({s: avg[s][0] for s in dates}) + ";"]
open(sys.argv[3], "w").write("\n".join(js) + "\n")
print("written", sys.argv[3], "light/dark spread", round(spread, 2))
for s in ["17", "18", "13", "36"] + days[:2] + ["1"]: print(s, avg[s])
