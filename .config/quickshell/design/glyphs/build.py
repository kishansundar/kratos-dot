"""Build Swiss Glyphs from defs.py. Codepoints follow NAMES order (append-only).
Writes what the shell loads in place: <shell>/assets/fonts/SwissGlyphs.ttf and <shell>/Glyphs.qml (no copy step);
and the references for the design folder in OUT (default: this folder): SwissGlyphs.woff2, glyphs.json, svg/*.svg.
Run: python3 design/glyphs/build.py design/glyphs (needs shapely, fonttools, brotli); then restart the shell fully."""
import sys, json, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from defs import G, NAMES
from shapely.geometry import Polygon
from shapely.geometry.polygon import orient
from shapely.affinity import affine_transform
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
UPM=1024; PX=UPM//16; here=os.path.dirname(os.path.abspath(__file__)); out=sys.argv[1] if len(sys.argv)>1 else here
shell=os.path.normpath(os.path.join(here,'..','..')); font=os.path.join(shell,'assets','fonts','SwissGlyphs.ttf')
os.makedirs(out+'/svg',exist_ok=True)
polys=lambda g: [g] if isinstance(g,Polygon) else list(g.geoms)
order=['.notdef','space']+NAMES; fb=FontBuilder(UPM,isTTF=True); fb.setupGlyphOrder(order)
cmap={0x20:'space'}; mapping={}
for i,n in enumerate(NAMES): cmap[0xE000+i]=n; mapping[n]=0xE000+i
fb.setupCharacterMap(cmap)
p=TTGlyphPen(None)
for ring in [[(64,0),(64,960),(960,960),(960,0)],[(128,64),(896,64),(896,896),(128,896)]]:
    p.moveTo(ring[0]); [p.lineTo(q) for q in ring[1:]]; p.closePath()
glyphs={'.notdef':p.glyph(),'space':TTGlyphPen(None).glyph()}
for n in NAMES:
    pen=TTGlyphPen(None); d=''
    for poly in polys(affine_transform(G[n],[PX,0,0,-PX,0,UPM])):
        poly=orient(poly,sign=-1.0)
        for ring in [poly.exterior]+list(poly.interiors):
            pts=[(int(round(x)),int(round(y))) for x,y in list(ring.coords)[:-1]]
            pen.moveTo(pts[0]); [pen.lineTo(q) for q in pts[1:]]; pen.closePath()
    glyphs[n]=pen.glyph()
    for poly in polys(G[n]):
        for ring in [poly.exterior]+list(poly.interiors):
            d+='M'+' L'.join(f'{round(x,3):g} {round(y,3):g}' for x,y in list(ring.coords)[:-1])+'Z'
    open(f'{out}/svg/{n}.svg','w').write(f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16"><path fill="#111111" fill-rule="evenodd" d="{d}"/></svg>\n')
fb.setupGlyf(glyphs)
# Each glyph's left side bearing is its outline's left edge (xMin). With lsb 0 for all, renderers that place a glyph by its
# lsb (Qt with FreeType) drew every glyph shifted left by its xMin (the small chevron by 4.6 px, bluetooth 3.4, the
# tick 7): the advance stays the 16 px box, so only the drawing moves back to where defs.py puts it.
_glyf=fb.font['glyf']
_metrics={}
for n in order:
    g=_glyf[n]; g.recalcBounds(_glyf)
    _metrics[n]=(UPM, getattr(g,'xMin',0) if g.numberOfContours else 0)
fb.setupHorizontalMetrics(_metrics); fb.setupHorizontalHeader(ascent=UPM,descent=0)
fb.setupNameTable({'familyName':'Swiss Glyphs','styleName':'Regular','uniqueFontIdentifier':'SwissGlyphs-Regular-1.1','fullName':'Swiss Glyphs Regular','psName':'SwissGlyphs-Regular','version':'Version 1.100','copyright':'Swiss Glyphs for Quickshell Swiss, SIL OFL 1.1. NixOS snowflake geometry from NixOS/nixos-artwork, CC-BY 4.0.'})
fb.setupOS2(sTypoAscender=UPM,sTypoDescender=0,sTypoLineGap=0,usWinAscent=UPM,usWinDescent=0,sxHeight=512,sCapHeight=UPM,fsType=0); fb.setupPost()
fb.save(font); f=TTFont(font); f.flavor='woff2'; f.save(out+'/SwissGlyphs.woff2')
json.dump({n:f'U+{c:04X}' for n,c in mapping.items()},open(out+'/glyphs.json','w'),indent=1)
camel=lambda n: (lambda a: a[0]+''.join(x.capitalize() for x in a[1:]))(n.split('-'))
q='pragma Singleton\nimport QtQuick\n\n// Generated by build.py from defs.py. Do not edit. Swiss Glyphs, U+E000 onward, append-only.\nQtObject {\n'+'\n'.join(f'    readonly property string {camel(n)}: "\\u{c:04X}"' for n,c in mapping.items())+'\n}\n'
open(os.path.join(shell,'Glyphs.qml'),'w').write(q); print(len(NAMES),'glyphs ->',font,'and',os.path.join(shell,'Glyphs.qml'),'; references ->',out)
